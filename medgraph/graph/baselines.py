import time
from typing import Dict, Any
from .state import MedGraphState
from .arg_engine import arg_engine
from medgraph.rag import vector_store_instance
from medgraph.llm import llm_client
from medgraph.agents import (
    PlannerAgent,
    RetrievalAgent,
    KnowledgeGraphAgent,
    DrugSafetyAgent,
    ClinicalGuidelineAgent,
    EvidenceVerificationAgent,
    ResponseAgent
)

class BaselineLLMOnly:
    """Baseline 1: Standard LLM-Only without external retrieval or agents."""
    def execute(self, query: str) -> MedGraphState:
        start = time.time()
        sys_prompt = "You are a clinical assistant. Answer the user's medical question based solely on your internal knowledge."
        ans = llm_client.generate(sys_prompt, query, temperature=0.1)
        latency = round((time.time() - start) * 1000, 2)

        return {
            "query": query,
            "mode": "baseline_llm",
            "total_latency_ms": latency,
            "agents_invoked_count": 1,
            "active_agent_ids": ["llm_only"],
            "execution_trace": [
                {"agent_id": "llm_only", "agent_name": "Direct LLM", "role": "Direct Generation", "status": "completed", "latency_ms": latency, "summary": "Direct generation without external retrieval or verification"}
            ],
            "final_response": {
                "answer_markdown": ans,
                "confidence_score": 0.60,
                "confidence_level": "UNVERIFIED (LLM Only)",
                "citations": [],
                "disclaimer": "Generated by direct LLM without grounding or external clinical knowledge graph verification."
            }
        }

class BaselineTraditionalRAG:
    """Baseline 2: Traditional RAG (Vector Search -> Single LLM Prompt)."""
    def execute(self, query: str) -> MedGraphState:
        start = time.time()
        docs = vector_store_instance.search(query, top_k=3)
        doc_context = "\n".join([f"- {d['title']}: {d['content'][:250]}..." for d in docs])

        sys_prompt = f"You are a medical assistant. Answer the question based on the retrieved literature below:\n\n{doc_context}"
        ans = llm_client.generate(sys_prompt, query, temperature=0.1)
        latency = round((time.time() - start) * 1000, 2)

        return {
            "query": query,
            "mode": "baseline_rag",
            "total_latency_ms": latency,
            "agents_invoked_count": 2,
            "active_agent_ids": ["vector_retriever", "llm_generator"],
            "retrieval_output": {"documents": docs},
            "execution_trace": [
                {"agent_id": "vector_retriever", "agent_name": "Vector Store RAG", "role": "Document Retriever", "status": "completed", "latency_ms": round(latency * 0.3, 2), "summary": f"Retrieved {len(docs)} documents"},
                {"agent_id": "llm_generator", "agent_name": "LLM Generator", "role": "RAG Generator", "status": "completed", "latency_ms": round(latency * 0.7, 2), "summary": "Synthesized RAG response"}
            ],
            "final_response": {
                "answer_markdown": ans,
                "confidence_score": 0.78,
                "confidence_level": "MODERATE (Traditional RAG)",
                "citations": [{"source": d.get("source"), "id": d.get("id"), "title": d.get("title")} for d in docs],
                "disclaimer": "Generated using single-pass Traditional RAG without structured Knowledge Graph or dynamic multi-agent verification."
            }
        }

class BaselineFixedMultiAgent:
    """Baseline 3: Fixed Multi-Agent RAG (Executes all agents sequentially on every single query)."""
    def __init__(self):
        self.planner = PlannerAgent()
        self.retriever = RetrievalAgent()
        self.kg = KnowledgeGraphAgent()
        self.safety = DrugSafetyAgent()
        self.guideline = ClinicalGuidelineAgent()
        self.verifier = EvidenceVerificationAgent()
        self.response = ResponseAgent()

    def execute(self, query: str) -> MedGraphState:
        start = time.time()
        state: MedGraphState = {
            "query": query,
            "mode": "baseline_fixed_multiagent",
            "execution_trace": [],
            "total_latency_ms": 0.0,
            "agents_invoked_count": 7,
            "active_agent_ids": ["planner_agent", "retrieval_agent", "kg_agent", "drug_safety_agent", "guideline_agent", "verifier_agent", "response_agent"]
        }

        # Static execution of all 7 agents regardless of query complexity
        p_res = self.planner.execute(state)
        state["planner_output"] = p_res.get("planner_output", {})

        r_res = self.retriever.execute(state)
        state["retrieval_output"] = r_res.get("retrieval_output", {})

        kg_res = self.kg.execute(state)
        state["kg_output"] = kg_res.get("kg_output", {})

        ds_res = self.safety.execute(state)
        state["drug_safety_output"] = ds_res.get("drug_safety_output", {})

        gl_res = self.guideline.execute(state)
        state["guideline_output"] = gl_res.get("guideline_output", {})

        v_res = self.verifier.execute(state)
        state["verifier_output"] = v_res.get("verifier_output", {})

        rsp_res = self.response.execute(state)
        state["final_response"] = rsp_res.get("final_response", {})

        latency = round((time.time() - start) * 1000, 2)
        state["total_latency_ms"] = latency

        for agent in [self.planner, self.retriever, self.kg, self.safety, self.guideline, self.verifier, self.response]:
            state["execution_trace"].append({
                "agent_id": agent.name.lower().replace(" ", "_"),
                "agent_name": agent.name,
                "role": agent.role,
                "status": "completed",
                "latency_ms": round(latency / 7.0, 2),
                "summary": f"Executed in fixed static pipeline"
            })

        return state

def execute_medgraph_query(query: str, mode: str = "adaptive") -> MedGraphState:
    """Unified entry point to run queries in Adaptive mode or any of the 3 baselines."""
    if mode == "baseline_llm":
        return BaselineLLMOnly().execute(query)
    elif mode == "baseline_rag":
        return BaselineTraditionalRAG().execute(query)
    elif mode == "baseline_fixed_multiagent":
        return BaselineFixedMultiAgent().execute(query)
    else:
        return arg_engine.execute(query)
